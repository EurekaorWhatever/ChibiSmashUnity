using System.Collections.Generic;
using UnityEngine;

namespace ChibiClash.Netcode
{
    /// <summary>
    /// Sound effects player (design/audio/sfx-spec.md + sfx-events.md). Presentation only (green zone): it reads
    /// ChibiSimState and ChibiSimEvents and never writes them; its randomness (variant pick, pitch jitter) is FxRandom.
    ///
    /// One persistent instance (created on first use, DontDestroyOnLoad) serves menus and matches:
    ///   - clips: Resources.LoadAll&lt;AudioClip&gt;("Audio/Sfx") once, variants grouped by id (&lt;id&gt;_&lt;nn&gt;);
    ///   - mix table: Resources/Audio/sfx_meta.txt (bus, priority, max voices, cooldown, pitch jitter), generated by
    ///     tools/audio/gen_sfx.py;
    ///   - 24 pooled 2D AudioSources, bus caps + priority stealing (<see cref="ChibiVoiceSteal"/>), ducking, real time
    ///     (Time.unscaledTime; AudioSource playback ignores Time.timeScale, so hitstop / cinematic never bend SFX).
    /// Match rules (hits, dedupe, derived events, confirmed match end) live in <see cref="ChibiSfxRouter"/>.
    ///
    /// Menus: <c>ChibiAudio.PlayUi("core_ui_confirm")</c>. Matches: ChibiSimView calls BeginMatch / OnSimStep / EndMatch.
    /// Outside Play Mode every static call is a no-op (EditMode tests can build views safely).
    /// </summary>
    public sealed class ChibiAudio : MonoBehaviour
    {
        const int VoiceCount = 24;
        const float StopFadeSec = 0.08f;          // loop / replaced voice stop fade (sfx-events.md 6.4)
        const float EndConfirmTimeoutSec = 1.5f;  // play the match end anyway if confirmation never arrives
        const float PanWidth = 0.5f;              // sfx-events.md 7
        // Bus order = SfxBus: STG, CMB, PRJ, MOV, UI, AMB (sfx-events.md 5.1, 8.1). AMB never uses the pool (own sources).
        static readonly int[] BusCap = { 3, 12, 6, 4, 3, 1 };
        static readonly float[] BusFaderDb = { 0f, 0f, -2f, -4f, -3f, -2f };
        const int BusCount = 6;
        const float AmbFadeInSec = 1.5f, AmbFadeOutSec = 1.0f;   // sfx-events.md 8.1
        const string MasterKey = "ChibiClash.Audio.Master", SfxKey = "ChibiClash.Audio.Sfx";

        static ChibiAudio _inst;
        static Dictionary<string, SfxMeta> _meta;
        static Dictionary<string, AudioClip[]> _clips;
        static float _master = -1f, _sfx = -1f;

        sealed class Voice
        {
            public AudioSource Src;
            public SfxBus Bus;
            public float BaseLin = 1f;
            public bool Exempt;
            public int Tag;
            public float FadeStart = -1f;
            public float PanFrom, PanTo, PanStart, PanDur;   // pan sweep (PanDur 0 = static)
        }

        sealed class Duck
        {
            public float Start, Attack, Hold, Release, ReleaseAt = -1f;
            public bool Held;
            public SfxDuck Kind;
            public readonly float[] Db = new float[BusCount];
        }

        readonly Voice[] _voices = new Voice[VoiceCount];
        readonly SfxVoiceInfo[] _info = new SfxVoiceInfo[VoiceCount];
        readonly List<SfxRequest> _requests = new List<SfxRequest>(32);
        readonly List<SfxRequest> _pending = new List<SfxRequest>(16);
        readonly List<float> _pendingDue = new List<float>(16);
        readonly List<Duck> _ducks = new List<Duck>(4);
        readonly float[] _duckDb = new float[BusCount];
        // Stage ambience: two looping sources for crossfades, current gain / target per source (0..1).
        readonly AudioSource[] _amb = new AudioSource[2];
        readonly float[] _ambGain = new float[2], _ambTarget = new float[2];
        int _ambCur, _ambToken;
        readonly Dictionary<string, int> _lastVariant = new Dictionary<string, int>();
        readonly ChibiSfxCooldowns _cooldowns = new ChibiSfxCooldowns();
        readonly ChibiSfxRouter _router = new ChibiSfxRouter();
        readonly List<ChibiSimEvent> _one = new List<ChibiSimEvent>(1);
        readonly int[] _overrideCls = new int[2];
        IChibiSimFeed _feed;
        float _pendingEndSince = -1f;
        readonly HashSet<string> _warned = new HashSet<string>();

        // ---------------------------------------------------------------------------------------------------- volume

        /// <summary>Master volume 0..1 (persisted in PlayerPrefs; SaveData has no volume setting yet).</summary>
        public static float MasterVolume
        {
            get { if (_master < 0f) _master = PlayerPrefs.GetFloat(MasterKey, 1f); return _master; }
            set { _master = Mathf.Clamp01(value); PlayerPrefs.SetFloat(MasterKey, _master); }
        }

        /// <summary>SFX volume 0..1 on top of <see cref="MasterVolume"/> (persisted in PlayerPrefs).</summary>
        public static float SfxVolume
        {
            get { if (_sfx < 0f) _sfx = PlayerPrefs.GetFloat(SfxKey, 1f); return _sfx; }
            set { _sfx = Mathf.Clamp01(value); PlayerPrefs.SetFloat(SfxKey, _sfx); }
        }

        // ------------------------------------------------------------------------------------------------ static API

        /// <summary>The player, created on first use in Play Mode; null outside Play Mode.</summary>
        public static ChibiAudio Instance
        {
            get
            {
                if (_inst != null) return _inst;
                if (!Application.isPlaying) return null;
                var go = new GameObject("ChibiAudio");
                DontDestroyOnLoad(go);
                _inst = go.AddComponent<ChibiAudio>();
                return _inst;
            }
        }

        /// <summary>Play sound <paramref name="id"/> (centred unless a fighter is given and a match is bound).</summary>
        /// <param name="fighter">Owner fighter 0/1 for the per-fighter cooldown and stereo position; -1 none.</param>
        /// <param name="pitch">Playback pitch multiplier (the id's random jitter is added).</param>
        /// <param name="gainDb">Extra gain on top of the bus.</param>
        /// <example><code>ChibiAudio.Play("kaia_clang", fighter: 0);</code></example>
        public static void Play(string id, int fighter = -1, float pitch = 1f, float gainDb = 0f)
        {
            var a = Instance;
            if (a == null || string.IsNullOrEmpty(id)) return;
            var r = SfxRequest.Of(id, fighter, pitch, gainDb);
            a.Pan(ref r);
            a.StartVoice(r, Time.unscaledTime);
        }

        /// <summary>
        /// Menu sound on the UI bus, usable with no match (sfx-events.md 5.4): core_ui_navigate (cursor, tab, scroll;
        /// slider step: pitch 1.1), core_ui_confirm, core_ui_back, core_ui_error, core_ui_lockin.
        /// </summary>
        /// <example><code>ChibiAudio.PlayUi("core_ui_confirm");</code></example>
        public static void PlayUi(string id, float pitch = 1f)
        {
            var a = Instance;
            if (a == null || string.IsNullOrEmpty(id)) return;
            var r = SfxRequest.Of(id, -1, pitch);
            r.Bus = SfxBus.UI;
            a.StartVoice(r, Time.unscaledTime);
        }

        /// <summary>Move start sound by animation kind (sfx-events.md 3.1), light version, centred.</summary>
        /// <example><code>ChibiAudio.PlayMove(FighterClass.Melee, "upswing");</code></example>
        public static void PlayMove(FighterClass cls, string animKind) => PlayMove(cls, animKind, false, -1);

        /// <summary>
        /// Move start sound by animation kind: jab, swing, upswing, lowsweep, thrust, slam, spin, shoot, cast, dive,
        /// uppercut, guard, rush, launch. <paramref name="heavy"/> = smash / charged / jab finisher. With a fighter
        /// index (0/1) the sound is panned and slam / dive arm the landing contact layer (kaia_thrak, bruna_thoom...).
        /// </summary>
        /// <example><code>ChibiAudio.PlayMove(FighterClass.Heavy, "slam", heavy: true, fighter: 1);</code></example>
        public static void PlayMove(FighterClass cls, string animKind, bool heavy, int fighter)
        {
            var a = Instance;
            if (a == null) return;
            float now = Time.unscaledTime;
            a._requests.Clear();
            if (!ChibiSfxMap.Move(cls, animKind, heavy, fighter, a._requests)) { a.WarnOnce("move kind " + animKind); return; }
            var s = a._feed?.State;
            if ((animKind == "slam" || animKind == "dive") && s != null && fighter >= 0 && fighter < ChibiSimEvents.Fighters(s))
                a._router.ArmContact(fighter, s.F[fighter].MoveSlot, now);
            a.Flush(now);
        }

        /// <summary>Bind a match feed (offline loop or online runner). Called by ChibiSimView.Begin.</summary>
        public static void BeginMatch(IChibiSimFeed feed)
        {
            var a = Instance;
            if (a == null) return;
            a._feed = feed;
            a._router.Reset();
            a._router.NeedsConfirm = feed is ChibiOnlineMatchRunner;
            a._pendingEndSince = -1f;
            a._cooldowns.Clear();
            a.StopAllMatchVoices();
        }

        /// <summary>Unbind <paramref name="feed"/> (ChibiSimView.OnDestroy). Loops stop; one-shots finish.</summary>
        public static void EndMatch(IChibiSimFeed feed)
        {
            if (_inst == null || _inst._feed != feed) return;
            _inst._feed = null;
            _inst.StopAllMatchVoices();
        }

        /// <summary>
        /// Feed one view step: <paramref name="events"/>[first..] came from ChibiSimEvents.Diff(prev, cur). Call it
        /// before the view overwrites prev. Derived events (jump, land, guard break, crit, ult ready) come from prev/cur.
        /// </summary>
        public static void OnSimStep(ChibiSimState prev, ChibiSimState cur, List<ChibiSimEvent> events, int first)
        {
            var a = _inst != null ? _inst : Instance;
            if (a == null || prev == null || cur == null || events == null) return;
            float now = Time.unscaledTime;
            a.ResolveLocal();
            a._requests.Clear();
            a._router.Step(prev, cur, events, first, now, a._requests);
            a.Flush(now);
        }

        /// <summary>
        /// Single-event entry with explicit classes (per-character layers resolve from <paramref name="c0"/> /
        /// <paramref name="c1"/>). No derived events (no prev state). Needs a bound match for positions.
        /// </summary>
        public static void OnSimEvent(in ChibiSimEvent e, FighterClass c0, FighterClass c1)
        {
            var a = Instance;
            var s = a?._feed?.State;
            if (s == null) return;
            float now = Time.unscaledTime;
            a._one.Clear();
            a._one.Add(e);
            a._overrideCls[0] = (int)c0;
            a._overrideCls[1] = (int)c1;
            a._router.ClassOverride = a._overrideCls;
            a._requests.Clear();
            a._router.Step(s, s, a._one, 0, now, a._requests);
            a._router.ClassOverride = null;
            a.Flush(now);
        }

        // ------------------------------------------------------------------------------------------------- stage audio

        /// <summary>
        /// Start the ambience bed of sim stage <paramref name="stage"/> (sfx-events.md 8.1): a seamless loop on its own
        /// source, faded in over 1.5 s, crossfading from any bed already playing. Stages without a bed fade the current one
        /// out. Returns a token for <see cref="StopAmbience(int)"/>; 0 outside Play Mode.
        /// </summary>
        /// <example><code>_ambToken = ChibiAudio.PlayAmbience(ChibiStageTable.Volcano);</code></example>
        public static int PlayAmbience(int stage)
        {
            var a = Instance;
            if (a == null) return 0;
            a._ambToken++;
            string id = ChibiStageSfx.AmbienceId(stage);
            AudioClip clip = null;
            if (id != null)
            {
                if (_clips != null && _clips.TryGetValue(id, out var clips) && clips.Length > 0) clip = clips[0];
                else a.WarnOnce(id);
            }
            var cur = a._amb[a._ambCur];
            if (clip != null && cur.clip == clip && cur.isPlaying)
            {
                a._ambTarget[a._ambCur] = 1f;   // same bed (rematch on the same stage): keep it running
                return a._ambToken;
            }
            a._ambTarget[a._ambCur] = 0f;
            if (clip == null) return a._ambToken;
            a._ambCur ^= 1;
            var src = a._amb[a._ambCur];
            src.Stop();
            src.clip = clip;
            src.loop = true;
            src.volume = 0f;
            src.time = FxRandom.Value * clip.length * 0.99f;   // random start: two visits never sound identical
            src.Play();
            a._ambGain[a._ambCur] = 0f;
            a._ambTarget[a._ambCur] = 1f;
            return a._ambToken;
        }

        /// <summary>Fade the ambience bed out (1 s).</summary>
        public static void StopAmbience()
        {
            if (_inst == null) return;
            _inst._ambTarget[0] = _inst._ambTarget[1] = 0f;
        }

        /// <summary>
        /// Fade the bed out only if <paramref name="token"/> (from <see cref="PlayAmbience"/>) is still the latest one, so a
        /// stage destroyed after its replacement was built does not silence the new bed.
        /// </summary>
        public static void StopAmbience(int token)
        {
            if (_inst != null && token != 0 && token == _inst._ambToken) StopAmbience();
        }

        /// <summary>
        /// Stage hazard sounds for the displayed state (sfx-events.md 8.2). <paramref name="tracker"/> belongs to the stage
        /// view and dedupes per (HazCount, phase), so calling this every frame plays each phase change once, rollback included.
        /// </summary>
        /// <example><code>ChibiAudio.StageHazard(_stageSfx, state);</code></example>
        public static void StageHazard(ChibiStageSfx tracker, ChibiSimState s)
        {
            if (tracker == null || s == null) return;
            var a = Instance;
            if (a == null) return;
            float now = Time.unscaledTime;
            a._requests.Clear();
            tracker.Step(s, a._requests);
            a.Flush(now);
        }

        // ------------------------------------------------------------------------------------------------- lifetime

        void Awake()
        {
            if (_inst != null && _inst != this) { Destroy(this); return; }
            _inst = this;
            // The game scene has no AudioListener (verified in Play Mode 2026-11-10: zero listeners), so nothing would be
            // heard. All SFX are 2D (spatialBlend 0), so the listener's position does not matter: keep it on this
            // persistent object unless the scene already provides one.
            if (FindAnyObjectByType<AudioListener>() == null) gameObject.AddComponent<AudioListener>();
            LoadLibrary();
            for (int i = 0; i < VoiceCount; i++)
            {
                var src = gameObject.AddComponent<AudioSource>();
                src.playOnAwake = false;
                src.spatialBlend = 0f;           // 2D, no distance attenuation (sfx-spec.md 1.3)
                src.ignoreListenerPause = false;
                _voices[i] = new Voice { Src = src };
            }
            for (int k = 0; k < _amb.Length; k++)
            {
                var src = gameObject.AddComponent<AudioSource>();
                src.playOnAwake = false;
                src.spatialBlend = 0f;
                src.loop = true;
                src.priority = 16;               // a bed is never culled by Unity's real-voice limit
                _amb[k] = src;
            }
        }

        static void LoadLibrary()
        {
            if (_clips != null) return;
            var table = Resources.Load<TextAsset>("Audio/sfx_meta");
            _meta = SfxMetaTable.Parse(table != null ? table.text : null);
            var groups = new Dictionary<string, List<AudioClip>>();
            foreach (var clip in Resources.LoadAll<AudioClip>("Audio/Sfx"))
            {
                string id = VariantId(clip.name);
                if (!groups.TryGetValue(id, out var list)) groups[id] = list = new List<AudioClip>();
                list.Add(clip);
            }
            _clips = new Dictionary<string, AudioClip[]>();
            foreach (var kv in groups)
            {
                kv.Value.Sort((x, y) => string.CompareOrdinal(x.name, y.name));
                _clips[kv.Key] = kv.Value.ToArray();
            }
            if (_clips.Count == 0) Debug.LogWarning("ChibiAudio: no clips under Resources/Audio/Sfx (run tools/audio/gen_sfx.py)");
        }

        /// <summary>"kaia_swish_03" -> "kaia_swish"; names without a two-digit suffix (loops) are their own id.</summary>
        public static string VariantId(string clipName)
        {
            int n = clipName.Length;
            if (n > 3 && clipName[n - 3] == '_' && char.IsDigit(clipName[n - 2]) && char.IsDigit(clipName[n - 1]))
                return clipName.Substring(0, n - 3);
            return clipName;
        }

        void OnDestroy() { if (_inst == this) _inst = null; }

        void ResolveLocal()
        {
            var runner = _feed as ChibiOnlineMatchRunner;
            var session = runner != null ? runner.Match?.Session : null;
            _router.LocalPlayer = session != null ? session.LocalIndex : -1;
        }

        void Update()
        {
            float now = Time.unscaledTime;
            _requests.Clear();
            if (_feed is Object o && o == null) { _feed = null; StopAllMatchVoices(); }
            var live = _feed?.State;
            if (live != null)
            {
                _router.Intro(live.IntroRealTicks, _requests);
                if (live.CinematicRealTicks == 0) ReleaseDuck(SfxDuck.Cinematic, now);
                ConfirmEnd(live, now);
            }
            Flush(now);

            for (int i = _pending.Count - 1; i >= 0; i--)
            {
                if (_pendingDue[i] > now) continue;
                var r = _pending[i];
                _pending.RemoveAt(i);
                _pendingDue.RemoveAt(i);
                StartVoice(r, now);
            }

            UpdateDucks(now);
            float master = MasterVolume * SfxVolume;
            for (int i = 0; i < VoiceCount; i++)
            {
                var v = _voices[i];
                if (!v.Src.isPlaying) continue;
                float fade = 1f;
                if (v.FadeStart >= 0f)
                {
                    fade = 1f - (now - v.FadeStart) / StopFadeSec;
                    if (fade <= 0f) { v.Src.Stop(); v.Src.loop = false; v.FadeStart = -1f; v.Tag = 0; continue; }
                }
                int b = (int)v.Bus;
                float duck = v.Exempt ? 0f : _duckDb[b];
                v.Src.volume = v.BaseLin * Db(BusFaderDb[b] + duck) * master * fade;
                if (v.PanDur > 0f) v.Src.panStereo = Mathf.Lerp(v.PanFrom, v.PanTo, (now - v.PanStart) / v.PanDur);
            }
            UpdateAmbience(master);
        }

        void UpdateAmbience(float master)
        {
            float dt = Time.unscaledDeltaTime;
            float bus = Db(BusFaderDb[(int)SfxBus.AMB] + _duckDb[(int)SfxBus.AMB]);
            for (int k = 0; k < _amb.Length; k++)
            {
                var src = _amb[k];
                if (src == null || src.clip == null) continue;
                float target = _ambTarget[k];
                _ambGain[k] = Mathf.MoveTowards(_ambGain[k], target, dt / (target > _ambGain[k] ? AmbFadeInSec : AmbFadeOutSec));
                if (_ambGain[k] <= 0f && target <= 0f)
                {
                    if (src.isPlaying) src.Stop();
                    continue;
                }
                // Equal-power fade curve, so a crossfade between two beds keeps the bed loudness steady.
                src.volume = Mathf.Sin(_ambGain[k] * Mathf.PI * 0.5f) * bus * master;
            }
        }

        void ConfirmEnd(ChibiSimState live, float now)
        {
            if (_router.PendingEndFrame < 0) { _pendingEndSince = -1f; return; }
            if (_pendingEndSince < 0f) _pendingEndSince = now;
            var runner = _feed as ChibiOnlineMatchRunner;
            var session = runner != null ? runner.Match?.Session : null;
            ChibiSimState final = null;
            if (session != null && session.ConfirmedFrame >= _router.PendingEndFrame)
            {
                var cs = session.ConfirmedState;
                if (cs != null && cs.MatchOver) final = cs;
            }
            if (final == null && live.MatchOver && (session == null || now - _pendingEndSince > EndConfirmTimeoutSec)) final = live;
            if (final != null) _router.ConfirmEnd(final.Winner, final.F[0].HpU <= 0 || final.F[1].HpU <= 0, _requests);
            else if (!live.MatchOver) { _router.CancelPendingEnd(); _pendingEndSince = -1f; }   // rolled back
        }

        // -------------------------------------------------------------------------------------------------- playback

        void Flush(float now)
        {
            for (int i = 0; i < _requests.Count; i++)
            {
                var r = _requests[i];
                Pan(ref r);
                StartVoice(r, now);
            }
            _requests.Clear();
        }

        void Pan(ref SfxRequest r)
        {
            var s = _feed?.State;
            if (s == null) { r.Panned = false; return; }
            if (!r.Panned && r.Fighter >= 0 && r.Fighter < ChibiSimEvents.Fighters(s)) { r.PanX = s.F[r.Fighter].X; r.Panned = true; }
        }

        float PanOf(in SfxRequest r)
        {
            var s = _feed?.State;
            if (!r.Panned || s == null) return 0f;
            int st = Mathf.Clamp(s.Stage, 0, ChibiStageTable.Stages.Length - 1);
            float half = Mathf.Max(1, ChibiStageTable.Stages[st].HalfWidth);
            return Mathf.Clamp(r.PanX / half, -1f, 1f) * PanWidth;
        }

        void StartVoice(SfxRequest r, float now)
        {
            if (r.StopTag != 0) StopTag(r.StopTag, now);
            if (string.IsNullOrEmpty(r.Id)) return;
            if (r.Delay > 0f)
            {
                float due = now + r.Delay;
                r.Delay = 0f;
                _pending.Add(r);
                _pendingDue.Add(due);
                return;
            }
            if (_meta == null || !_meta.TryGetValue(r.Id, out var m) || _clips == null || !_clips.TryGetValue(r.Id, out var clips) || clips.Length == 0)
            {
                WarnOnce(r.Id);
                return;
            }
            if (!_cooldowns.TryPass(r.Id, r.Fighter, now, m.CdMs)) return;
            var bus = r.Bus ?? m.Bus;
            for (int i = 0; i < VoiceCount; i++)
            {
                var v = _voices[i];
                _info[i].Busy = v.Src.isPlaying;
                _info[i].Bus = v.Bus;
            }
            int idx = ChibiVoiceSteal.Choose(_info, bus, BusCap[(int)bus], r.Id, m.Max, m.Pri);
            if (idx < 0) return;

            int k = 0;
            if (clips.Length > 1)
            {
                // Shuffle-bag lite: random variant, never the same one twice in a row (sfx-events.md 1.3).
                _lastVariant.TryGetValue(r.Id, out int last);
                k = Mathf.Min(clips.Length - 2, (int)(FxRandom.Value * (clips.Length - 1)));
                if (k >= last) k++;
            }
            _lastVariant[r.Id] = k;

            var voice = _voices[idx];
            var src = voice.Src;
            src.Stop();
            src.clip = clips[k];
            src.loop = r.Loop;
            float jitter = m.PitchPct > 0f ? FxRandom.Range(-m.PitchPct, m.PitchPct) / 100f : 0f;
            src.pitch = Mathf.Max(0.1f, (r.Pitch <= 0f ? 1f : r.Pitch) * (1f + jitter));
            src.panStereo = PanOf(r);
            voice.PanDur = 0f;
            if (r.PanSweepSec > 0f && r.Panned)
            {
                var end = r;
                end.PanX = r.PanEndX;
                voice.PanFrom = src.panStereo;
                voice.PanTo = PanOf(end);
                voice.PanStart = now;
                voice.PanDur = r.PanSweepSec;
            }
            voice.Bus = bus;
            voice.BaseLin = Db(r.GainDb);
            voice.Exempt = r.Exempt;
            voice.Tag = r.Tag;
            voice.FadeStart = -1f;
            src.volume = voice.BaseLin * Db(BusFaderDb[(int)bus] + (r.Exempt ? 0f : _duckDb[(int)bus])) * MasterVolume * SfxVolume;
            src.Play();
            _info[idx] = new SfxVoiceInfo { Busy = true, Bus = bus, Pri = m.Pri, Start = now, Id = r.Id };
            if (r.Duck != SfxDuck.None) StartDuck(r.Duck, now);
        }

        void StopTag(int tag, float now)
        {
            for (int i = 0; i < VoiceCount; i++)
                if (_voices[i].Tag == tag && _voices[i].Src.isPlaying && _voices[i].FadeStart < 0f) _voices[i].FadeStart = now;
            for (int i = _pending.Count - 1; i >= 0; i--)
                if (_pending[i].Tag == tag) { _pending.RemoveAt(i); _pendingDue.RemoveAt(i); }
        }

        void StopAllMatchVoices()
        {
            float now = Time.unscaledTime;
            for (int i = 0; i < VoiceCount; i++)
                if (_voices[i] != null && _voices[i].Src.loop && _voices[i].Src.isPlaying) _voices[i].FadeStart = now;
            for (int i = _pending.Count - 1; i >= 0; i--)
                if (_pending[i].Bus != SfxBus.UI) { _pending.RemoveAt(i); _pendingDue.RemoveAt(i); }
            _ducks.Clear();
        }

        // ----------------------------------------------------------------------------------------------------- ducks

        void StartDuck(SfxDuck kind, float now)
        {
            var d = new Duck { Kind = kind, Start = now };
            switch (kind)
            {
                case SfxDuck.Ko:          // CMB/PRJ/MOV -12, UI -6, 20 / 1400 / 600 ms
                    d.Attack = 0.02f; d.Hold = 1.4f; d.Release = 0.6f;
                    d.Db[(int)SfxBus.CMB] = d.Db[(int)SfxBus.PRJ] = d.Db[(int)SfxBus.MOV] = -12f; d.Db[(int)SfxBus.UI] = -6f;
                    d.Db[(int)SfxBus.AMB] = -8f;
                    break;
                case SfxDuck.StockKo:     // a stock lost mid-match (8.3): CMB/PRJ/MOV -8, AMB -6, 10 / 600 / 400 ms
                    d.Attack = 0.01f; d.Hold = 0.6f; d.Release = 0.4f;
                    d.Db[(int)SfxBus.CMB] = d.Db[(int)SfxBus.PRJ] = d.Db[(int)SfxBus.MOV] = -8f; d.Db[(int)SfxBus.AMB] = -6f;
                    break;
                case SfxDuck.Cinematic:   // CMB/PRJ/MOV -9, 30 ms / until CinematicRealTicks = 0 / 250 ms
                    ReleaseDuck(SfxDuck.Cinematic, now);
                    d.Attack = 0.03f; d.Held = true; d.Release = 0.25f;
                    d.Db[(int)SfxBus.CMB] = d.Db[(int)SfxBus.PRJ] = d.Db[(int)SfxBus.MOV] = -9f; d.Db[(int)SfxBus.AMB] = -6f;
                    break;
                case SfxDuck.HitAccent:   // guard break / crit: MOV/PRJ -4, 10 / 100 / 150 ms
                    d.Attack = 0.01f; d.Hold = 0.1f; d.Release = 0.15f;
                    d.Db[(int)SfxBus.MOV] = d.Db[(int)SfxBus.PRJ] = -4f;
                    break;
                case SfxDuck.RingOut:     // MOV -6, 10 / 300 / 300 ms
                    d.Attack = 0.01f; d.Hold = 0.3f; d.Release = 0.3f;
                    d.Db[(int)SfxBus.MOV] = -6f;
                    break;
            }
            _ducks.Add(d);
        }

        void ReleaseDuck(SfxDuck kind, float now)
        {
            for (int i = 0; i < _ducks.Count; i++)
                if (_ducks[i].Kind == kind && _ducks[i].Held && _ducks[i].ReleaseAt < 0f) _ducks[i].ReleaseAt = now;
        }

        void UpdateDucks(float now)
        {
            for (int b = 0; b < _duckDb.Length; b++) _duckDb[b] = 0f;
            for (int i = _ducks.Count - 1; i >= 0; i--)
            {
                var d = _ducks[i];
                float t = now - d.Start, w;
                float relStart = d.Held ? (d.ReleaseAt < 0f ? float.MaxValue : d.ReleaseAt - d.Start) : d.Attack + d.Hold;
                if (t < d.Attack) w = t / d.Attack;
                else if (t < relStart) w = 1f;
                else w = 1f - (t - relStart) / Mathf.Max(0.001f, d.Release);
                if (w <= 0f && t >= relStart) { _ducks.RemoveAt(i); continue; }
                w = Mathf.Clamp01(w);
                // Ducks do not stack: the deepest active one per bus wins (sfx-events.md 5.3).
                for (int b = 0; b < _duckDb.Length; b++) _duckDb[b] = Mathf.Min(_duckDb[b], d.Db[b] * w);
            }
        }

        static float Db(float db) => Mathf.Pow(10f, db / 20f);

        void WarnOnce(string what)
        {
            if (_warned.Add(what)) Debug.LogWarning("ChibiAudio: unknown or missing sound '" + what + "'");
        }
