using System.Collections.Generic;
using UnityEngine;

namespace ChibiClash
{
    /// <summary>One frame-by-frame animation: frames sliced from a single-row sprite sheet, played at a fixed rate.</summary>
    public sealed class SpriteClip
    {
        public string name;
        public Sprite[] frames;
        public float fps = 24f;
        public bool loop;

        /// <summary>Natural length in seconds (frames / fps).</summary>
        public float Length => frames.Length / fps;

        /// <summary>Frame at time <paramref name="t"/> seconds (wraps when looping, otherwise holds the last frame).</summary>
        public Sprite Frame(float t)
        {
            int i = Mathf.FloorToInt(t * fps);
            i = loop ? ((i % frames.Length) + frames.Length) % frames.Length : Mathf.Clamp(i, 0, frames.Length - 1);
            return frames[i];
        }

        /// <summary>Frame at normalised progress <paramref name="u"/> (0..1 across the whole clip).</summary>
        public Sprite FrameNormalized(float u)
        {
            int i = Mathf.FloorToInt(u * frames.Length);
            i = loop ? ((i % frames.Length) + frames.Length) % frames.Length : Mathf.Clamp(i, 0, frames.Length - 1);
            return frames[i];
        }
    }

    /// <summary>
    /// Frame-by-frame sprite sheets per character, keyed by <see cref="CharacterInfo.Id"/>:
    /// Resources/Animations/&lt;Id&gt;/&lt;Clip&gt;.png, one horizontal row of evenly spaced 384x256 frames, character facing
    /// right, feet at the horizontal centre <see cref="FeetPivot"/> above the bottom (generated by tools/art/gen_cutout_anims.py).
    /// The frame count is the clip's default (<see cref="DefaultFrames"/>) or is given in the file name: Swing_12.png = 12
    /// frames. Missing clips return null and the caller falls back to the procedural animation.
    /// Everything is loaded and sliced once per character; lookups afterwards are allocation-free.
    /// </summary>
    public static class SpriteAnimLibrary
    {
        public const float Fps = 24f;
        /// <summary>Fraction of the frame height that the standing character fills (generator: FIG = 0.78 H).</summary>
        public const float FigureFill = 0.78f;
        /// <summary>Where the feet sit in a frame, as a fraction of the frame height from the bottom.</summary>
        public const float FeetPivot = 0.04f;

        /// <summary>Every clip name the runtime understands (basic, the three class moves, then the generic attack set).</summary>
        public static readonly string[] Clips =
        {
            "Idle", "Run", "Jump", "Hit", "KO", "Victory", "Skill1", "Skill2", "Ultimate",
            "Jab", "Swing", "Upswing", "LowSweep", "Thrust", "Slam", "Spin", "Shoot", "Cast",
            "Dive", "Uppercut", "Guard", "Rush", "Launch", "Dash",
        };

        static readonly Dictionary<string, Dictionary<string, SpriteClip>> cache =
            new Dictionary<string, Dictionary<string, SpriteClip>>(System.StringComparer.OrdinalIgnoreCase);
        static readonly Dictionary<string, Sprite> bodies = new Dictionary<string, Sprite>(System.StringComparer.OrdinalIgnoreCase);

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
        static void ResetStatics()
        {
            cache.Clear();
            bodies.Clear();
        }

        /// <summary>Frame count of a clip whose file name does not carry one (must match the generator).</summary>
        public static int DefaultFrames(string clip)
        {
            switch (clip)
            {
                case "Hit": return 6;
                case "Guard": return 6;
                case "KO": return 10;
                case "Jab": return 8;
                case "Dash": return 8;
                case "Skill1":
                case "Skill2": return 14;
                case "Slam":
                case "Spin":
                case "Cast": return 12;
                case "Swing":
                case "Upswing":
                case "LowSweep":
                case "Thrust":
                case "Shoot":
                case "Dive":
                case "Uppercut":
                case "Rush":
                case "Launch": return 10;
                case "Ultimate": return 28;
                default: return 8;
            }
        }

        public static bool Loops(string clip) => clip == "Idle" || clip == "Run" || clip == "Victory";

        /// <summary>The clip, or null when no sheet exists for it (or <paramref name="characterId"/> is empty).</summary>
        public static SpriteClip Get(string characterId, string clip)
        {
            if (string.IsNullOrEmpty(characterId) || clip == null) return null;
            if (!cache.TryGetValue(characterId, out var clips))
            {
                clips = Load(characterId);
                cache[characterId] = clips;
            }
            return clips.TryGetValue(clip, out var c) ? c : null;
        }

        /// <summary>True when at least one sheet exists for the character.</summary>
        public static bool HasAny(string characterId)
        {
            if (string.IsNullOrEmpty(characterId)) return false;
            Get(characterId, "Idle");
            return cache[characterId].Count > 0;
        }

        /// <summary>Full-body front drawing Resources/Characters/&lt;Id&gt; (1024x1024, feet at 1010 px), or null.</summary>
        public static Sprite Body(string characterId)
        {
            if (string.IsNullOrEmpty(characterId)) return null;
            if (bodies.TryGetValue(characterId, out var s)) return s;
            s = Resources.Load<Sprite>("Characters/" + characterId);
            if (s == null)
            {
                var tex = Resources.Load<Texture2D>("Characters/" + characterId);
                if (tex != null) s = Sprite.Create(tex, new Rect(0, 0, tex.width, tex.height), new Vector2(0.5f, 0.5f), 100f);
            }
            bodies[characterId] = s;
            return s;
        }

        static Dictionary<string, SpriteClip> Load(string characterId)
        {
            var result = new Dictionary<string, SpriteClip>();
            var textures = Resources.LoadAll<Texture2D>("Animations/" + characterId);
            foreach (var tex in textures)
            {
                string name = tex.name;
                int frames = 0;
                int us = name.LastIndexOf('_');
                if (us > 0 && int.TryParse(name.Substring(us + 1), out int n) && n > 0)
                {
                    frames = n;
                    name = name.Substring(0, us);
                }
                string clip = Canonical(name);
                if (clip == null)
                {
                    Debug.LogWarning("ChibiClash: unknown animation sheet '" + tex.name + "' for " + characterId);
                    continue;
                }
                if (frames <= 0) frames = DefaultFrames(clip);
                frames = Mathf.Clamp(frames, 1, Mathf.Max(1, tex.width));
                float fw = tex.width / (float)frames;
                var sprites = new Sprite[frames];
                for (int i = 0; i < frames; i++)
                {
                    var rect = new Rect(Mathf.Round(i * fw), 0f, Mathf.Floor(fw), tex.height);
                    // pixels-per-unit = frame height, so one frame is exactly 1 world unit tall
                    sprites[i] = Sprite.Create(tex, rect, new Vector2(0.5f, FeetPivot), tex.height, 0, SpriteMeshType.FullRect);
                    sprites[i].name = tex.name + "_" + i;
                }
                result[clip] = new SpriteClip { name = clip, frames = sprites, fps = Fps, loop = Loops(clip) };
            }
            return result;
        }

        static string Canonical(string name)
        {
            foreach (var c in Clips)
                if (string.Equals(c, name, System.StringComparison.OrdinalIgnoreCase)) return c;
            switch (name.ToLowerInvariant())
            {
                case "side": return "Skill1";
                case "down": return "Skill2";
                case "ult": return "Ultimate";
                default: return null;
            }
        }
    }
}
