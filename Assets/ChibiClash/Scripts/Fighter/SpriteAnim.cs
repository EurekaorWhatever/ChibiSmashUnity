using System.Collections.Generic;
using UnityEngine;

namespace ChibiClash
{
    /// <summary>One frame-by-frame animation: frames sliced from a single-row sprite sheet, played at a fixed rate.</summary>
    public sealed class SpriteClip
    {
        public string name;
        public Sprite[] frames;
        public float fps = 24f;
        public bool loop;

        /// <summary>
        /// Sheet-pose move clips only (clips.txt): first frame that shows the hit, and the first recovery frame. -1 when
        /// the clip has no phase data (it is then stretched linearly).
        /// </summary>
        public int strikeFrame = -1, recoverFrame = -1;

        /// <summary>Natural length in seconds (frames / fps).</summary>
        public float Length => frames.Length / fps;

        /// <summary>True when <see cref="FramePhased"/> can line the strike frame up with a move's first active frame.</summary>
        public bool HasPhases => strikeFrame > 0 && recoverFrame > strikeFrame && recoverFrame <= frames.Length;

        /// <summary>
        /// Frame at time <paramref name="t"/> of a move with the given startup / active / recovery lengths (seconds):
        /// frames [0, strike) play over the startup, [strike, recover) over the active window, the rest over the
        /// recovery, so the strike frame lands exactly on the first active frame. Holds the last frame afterwards.
        /// </summary>
        public Sprite FramePhased(float t, float startup, float active, float recovery)
        {
            float u;
            if (t < startup) u = startup > 0f ? t / startup * strikeFrame : strikeFrame;
            else if (t < startup + active) u = strikeFrame + (t - startup) / Mathf.Max(1e-4f, active) * (recoverFrame - strikeFrame);
            else u = recoverFrame + (t - startup - active) / Mathf.Max(1e-4f, recovery) * (frames.Length - recoverFrame);
            return frames[Mathf.Clamp(Mathf.FloorToInt(u), 0, frames.Length - 1)];
        }

        /// <summary>Frame at time <paramref name="t"/> seconds (wraps when looping, otherwise holds the last frame).</summary>
        public Sprite Frame(float t)
        {
            int i = Mathf.FloorToInt(t * fps);
            i = loop ? ((i % frames.Length) + frames.Length) % frames.Length : Mathf.Clamp(i, 0, frames.Length - 1);
            return frames[i];
        }

        /// <summary>Frame at normalised progress <paramref name="u"/> (0..1 across the whole clip).</summary>
        public Sprite FrameNormalized(float u)
        {
            int i = Mathf.FloorToInt(u * frames.Length);
            i = loop ? ((i % frames.Length) + frames.Length) % frames.Length : Mathf.Clamp(i, 0, frames.Length - 1);
            return frames[i];
        }
    }

    /// <summary>
    /// Frame-by-frame sprite sheets per character, keyed by <see cref="CharacterInfo.Id"/>:
    /// Resources/Animations/&lt;Id&gt;/&lt;Clip&gt;.png, one horizontal row of evenly spaced 384x256 frames, character facing
    /// right, feet at the horizontal centre <see cref="FeetPivot"/> above the bottom (generated by tools/art/gen_cutout_anims.py).
    /// The frame count is the clip's default (<see cref="DefaultFrames"/>) or is given in the file name: Swing_12.png = 12
    /// frames. Sheet-pose clips (tools/art/sheet_anims.py) are keyed by file name, Move_&lt;moveId&gt; per move and
    /// Idle_Sheet (which also serves "Idle"), with <see cref="MoveFrameAspect"/>-wide frames.
    /// Missing clips return null and the caller falls back to the procedural animation.
    /// Everything is loaded and sliced once per character; lookups afterwards are allocation-free.
    /// </summary>
    public static class SpriteAnimLibrary
    {
        public const float Fps = 24f;
        /// <summary>Fraction of the frame height that the standing character fills (generator: FIG = 0.78 H).</summary>
        public const float FigureFill = 0.78f;
        /// <summary>Where the feet sit in a frame, as a fraction of the frame height from the bottom.</summary>
        public const float FeetPivot = 0.04f;
        /// <summary>
        /// Frame width / height of the sheet-pose clips (tools/art/sheet_anims.py): Move_&lt;moveId&gt;.png and
        /// Idle_Sheet.png use 640x256 frames so the drawn slash arcs fit; their frame count is width / (height * this)
        /// unless clips.txt gives it.
        /// </summary>
        public const float MoveFrameAspect = 2.5f;
        /// <summary>Default rate of the sheet-pose clips when clips.txt does not give one (the generator draws 30 fps).</summary>
        public const float PosedFps = 30f;
        /// <summary>
        /// Per-character TextAsset Resources/Animations/&lt;Id&gt;/clips(.txt) written by the generator, one line per
        /// sheet-pose clip: "name frameCount fps strikeFrame recoverFrame [columns]" ('#' starts a comment, -1 = none).
        /// With columns the sheet is a grid (frames left to right, top to bottom) so no texture side exceeds 4096 px.
        /// </summary>
        public const string ClipTable = "clips";
        /// <summary>File-name prefix of a per-move clip: Resources/Animations/&lt;Id&gt;/Move_&lt;moveId&gt;.png.</summary>
        public const string MovePrefix = "Move_";
        /// <summary>Idle loop cut from the sheet's Idle panel; when present it also serves as "Idle".</summary>
        public const string IdleSheet = "Idle_Sheet";

        /// <summary>Every clip name the runtime understands (basic, the three class moves, then the generic attack set).</summary>
        public static readonly string[] Clips =
        {
            "Idle", "Run", "Jump", "Hit", "KO", "Victory", "Skill1", "Skill2", "Ultimate",
            "Jab", "Swing", "Upswing", "LowSweep", "Thrust", "Slam", "Spin", "Shoot", "Cast",
            "Dive", "Uppercut", "Guard", "Rush", "Launch", "Dash",
        };

        static readonly Dictionary<string, Dictionary<string, SpriteClip>> cache =
            new Dictionary<string, Dictionary<string, SpriteClip>>(System.StringComparer.OrdinalIgnoreCase);
        static readonly Dictionary<string, Sprite> bodies = new Dictionary<string, Sprite>(System.StringComparer.OrdinalIgnoreCase);

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
        static void ResetStatics()
        {
            cache.Clear();
            bodies.Clear();
            moveNames.Clear();
        }

        static readonly Dictionary<string, string> moveNames = new Dictionary<string, string>(System.StringComparer.Ordinal);

        /// <summary>
        /// Clip name of a move's sheet-pose clip ("Move_" + <paramref name="moveId"/>), cached so repeated lookups do not
        /// allocate. Null for an empty id.
        /// </summary>
        public static string MoveClipName(string moveId)
        {
            if (string.IsNullOrEmpty(moveId)) return null;
            if (!moveNames.TryGetValue(moveId, out var n))
            {
                n = MovePrefix + moveId;
                moveNames[moveId] = n;
            }
            return n;
        }

        /// <summary>Frame count of a clip whose file name does not carry one (must match the generator).</summary>
        public static int DefaultFrames(string clip)
        {
            switch (clip)
            {
                case "Hit": return 6;
                case "Guard": return 6;
                case "KO": return 10;
                case "Jab": return 8;
                case "Dash": return 8;
                case "Skill1":
                case "Skill2": return 14;
                case "Slam":
                case "Spin":
                case "Cast": return 12;
                case "Swing":
                case "Upswing":
                case "LowSweep":
                case "Thrust":
                case "Shoot":
                case "Dive":
                case "Uppercut":
                case "Rush":
                case "Launch": return 10;
                case "Ultimate": return 28;
                default: return 8;
            }
        }

        public static bool Loops(string clip) => clip == "Idle" || clip == "Run" || clip == "Victory";

        /// <summary>The clip, or null when no sheet exists for it (or <paramref name="characterId"/> is empty).</summary>
        public static SpriteClip Get(string characterId, string clip)
        {
            if (string.IsNullOrEmpty(characterId) || clip == null) return null;
            if (!cache.TryGetValue(characterId, out var clips))
            {
                clips = Load(characterId);
                cache[characterId] = clips;
            }
            return clips.TryGetValue(clip, out var c) ? c : null;
        }

        /// <summary>True when at least one sheet exists for the character.</summary>
        public static bool HasAny(string characterId)
        {
            if (string.IsNullOrEmpty(characterId)) return false;
            Get(characterId, "Idle");
            return cache[characterId].Count > 0;
        }

        /// <summary>Full-body front drawing Resources/Characters/&lt;Id&gt; (1024x1024, feet at 1010 px), or null.</summary>
        public static Sprite Body(string characterId)
        {
            if (string.IsNullOrEmpty(characterId)) return null;
            if (bodies.TryGetValue(characterId, out var s)) return s;
            s = Resources.Load<Sprite>("Characters/" + characterId);
            if (s == null)
            {
                var tex = Resources.Load<Texture2D>("Characters/" + characterId);
                if (tex != null) s = Sprite.Create(tex, new Rect(0, 0, tex.width, tex.height), new Vector2(0.5f, 0.5f), 100f);
            }
            bodies[characterId] = s;
            return s;
        }

        static Dictionary<string, SpriteClip> Load(string characterId)
        {
            var result = new Dictionary<string, SpriteClip>();
            var textures = Resources.LoadAll<Texture2D>("Animations/" + characterId);
            var table = ReadClipTable(Resources.Load<TextAsset>("Animations/" + characterId + "/" + ClipTable));
            SpriteClip idleSheet = null;
            foreach (var tex in textures)
            {
                string name = tex.name;
                bool idle = string.Equals(name, IdleSheet, System.StringComparison.OrdinalIgnoreCase);
                if (idle || name.StartsWith(MovePrefix, System.StringComparison.OrdinalIgnoreCase))
                {
                    // sheet-pose clip: the file name is the key (Move_kaia_ftilt / Idle_Sheet); frames, rate and phases
                    // from clips.txt, else the fixed frame aspect at PosedFps
                    int pf = Mathf.Max(1, Mathf.RoundToInt(tex.width / (tex.height * MoveFrameAspect)));
                    float fps = PosedFps;
                    int strike = -1, recover = -1, cols = 0;
                    if (table != null && table.TryGetValue(name, out var row))
                    {
                        if (row.frames > 0) pf = row.frames;
                        if (row.fps > 0f) fps = row.fps;
                        strike = row.strike;
                        recover = row.recover;
                        cols = row.cols;
                    }
                    var pc = new SpriteClip { name = name, frames = Slice(tex, pf, cols), fps = fps, loop = idle,
                                              strikeFrame = strike, recoverFrame = recover };
                    result[name] = pc;
                    if (idle) idleSheet = pc;
                    continue;
                }
                int frames = 0;
                int us = name.LastIndexOf('_');
                if (us > 0 && int.TryParse(name.Substring(us + 1), out int n) && n > 0)
                {
                    frames = n;
                    name = name.Substring(0, us);
                }
                string clip = Canonical(name);
                if (clip == null)
                {
                    Debug.LogWarning("ChibiClash: unknown animation sheet '" + tex.name + "' for " + characterId);
                    continue;
                }
                if (frames <= 0) frames = DefaultFrames(clip);
                result[clip] = new SpriteClip { name = clip, frames = Slice(tex, frames), fps = Fps, loop = Loops(clip) };
            }
            // the sheet's idle drawing wins over the front-facing cutout idle
            if (idleSheet != null) result["Idle"] = new SpriteClip { name = "Idle", frames = idleSheet.frames, fps = idleSheet.fps, loop = true };
            return result;
        }

        struct ClipRow { public int frames, strike, recover, cols; public float fps; }

        /// <summary>Parses clips.txt ("name frameCount fps strikeFrame recoverFrame [columns]" per line); null when absent.</summary>
        static Dictionary<string, ClipRow> ReadClipTable(TextAsset asset)
        {
            if (asset == null) return null;
            var rows = new Dictionary<string, ClipRow>(System.StringComparer.OrdinalIgnoreCase);
            var inv = System.Globalization.CultureInfo.InvariantCulture;
            foreach (var raw in asset.text.Split('\n'))
            {
                string line = raw.Trim();
                if (line.Length == 0 || line[0] == '#') continue;
                var p = line.Split((char[])null, System.StringSplitOptions.RemoveEmptyEntries);
                if (p.Length < 5) continue;
                if (!int.TryParse(p[1], System.Globalization.NumberStyles.Integer, inv, out int f)) continue;
                float.TryParse(p[2], System.Globalization.NumberStyles.Float, inv, out float fps);
                int.TryParse(p[3], System.Globalization.NumberStyles.Integer, inv, out int s);
                int.TryParse(p[4], System.Globalization.NumberStyles.Integer, inv, out int r);
                int c = 0;
                if (p.Length > 5) int.TryParse(p[5], System.Globalization.NumberStyles.Integer, inv, out c);
                rows[p[0]] = new ClipRow { frames = f, fps = fps, strike = s, recover = r, cols = c };
            }
            return rows;
        }

        /// <summary>
        /// Cuts a sheet into <paramref name="frames"/> evenly spaced sprites (feet pivot, 1 unit tall): one row, or a grid
        /// of <paramref name="columns"/> per row read left to right, top to bottom (columns &lt;= 0 = one row).
        /// </summary>
        static Sprite[] Slice(Texture2D tex, int frames, int columns = 0)
        {
            frames = Mathf.Clamp(frames, 1, Mathf.Max(1, tex.width));
            int cols = columns > 0 ? Mathf.Min(columns, frames) : frames;
            int rows = (frames + cols - 1) / cols;
            float fw = tex.width / (float)cols;
            float fh = tex.height / (float)rows;
            var sprites = new Sprite[frames];
            for (int i = 0; i < frames; i++)
            {
                int c = i % cols, r = i / cols;
                // texture y runs bottom-up: row 0 is the top row of the sheet
                var rect = new Rect(Mathf.Round(c * fw), Mathf.Round(tex.height - (r + 1) * fh), Mathf.Floor(fw), Mathf.Floor(fh));
                // pixels-per-unit = frame height, so one frame is exactly 1 world unit tall
                sprites[i] = Sprite.Create(tex, rect, new Vector2(0.5f, FeetPivot), Mathf.Floor(fh), 0, SpriteMeshType.FullRect);
                sprites[i].name = tex.name + "_" + i;
            }
            return sprites;
        }

        static string Canonical(string name)
        {
            foreach (var c in Clips)
                if (string.Equals(c, name, System.StringComparison.OrdinalIgnoreCase)) return c;
            switch (name.ToLowerInvariant())
            {
                case "side": return "Skill1";
                case "down": return "Skill2";
                case "ult": return "Ultimate";
                default: return null;
            }
        }
    }
}
