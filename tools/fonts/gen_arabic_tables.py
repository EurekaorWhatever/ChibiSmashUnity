"""Generate Assets/ChibiClash/Scripts/Core/RtlTables.cs (Arabic joining types + presentation forms).

Usage:  python -P tools/fonts/gen_arabic_tables.py <ArabicShaping.txt>

<ArabicShaping.txt> is the Unicode Character Database file
https://www.unicode.org/Public/UCD/latest/ucd/ArabicShaping.txt (download it into a fresh folder).
Presentation forms come from Python's unicodedata decompositions (<isolated>/<final>/<initial>/<medial>) of
U+FB50..U+FDFF and U+FE70..U+FEFF. Only the Arabic blocks U+0600..U+08FF are tabulated.
"""
import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "Assets", "ChibiClash", "Scripts", "Core", "RtlTables.cs")
FIRST, LAST = 0x0600, 0x08FF


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    jt = {}
    with open(sys.argv[1], encoding="utf-8") as f:
        version = f.readline().strip("# \n")
        for line in f:
            line = line.split("#")[0].strip()
            if not line:
                continue
            parts = [p.strip() for p in line.split(";")]
            jt[int(parts[0], 16)] = parts[2]
    # Transparent: every non-spacing / enclosing mark and format char in the range (ArabicShaping.txt lists only
    # the explicit ones; the rest default to T for Mn, Me, Cf).
    types = []
    for c in range(FIRST, LAST + 1):
        t = jt.get(c)
        if t is None:
            cat = unicodedata.category(chr(c))
            t = "T" if cat in ("Mn", "Me", "Cf") else "U"
        types.append(t)
    forms = {}
    names = {"<isolated>": 0, "<final>": 1, "<initial>": 2, "<medial>": 3}
    for c in list(range(0xFB50, 0xFE00)) + list(range(0xFE70, 0xFF00)):
        d = unicodedata.decomposition(chr(c)).split()
        if len(d) != 2 or d[0] not in names:
            continue
        base = int(d[1], 16)
        if not FIRST <= base <= LAST:
            continue
        forms.setdefault(base, [0, 0, 0, 0])
        if forms[base][names[d[0]]] == 0:
            forms[base][names[d[0]]] = c
    rows = []
    for base in sorted(forms):
        iso, fin, ini, med = forms[base]
        rows.append("0x%04X, 0x%04X, 0x%04X, 0x%04X, 0x%04X," % (base, iso, fin, ini, med))
    body = "\n".join("            " + r for r in rows)
    jtypes = "".join(types)
    chunks = [jtypes[i:i + 96] for i in range(0, len(jtypes), 96)]
    jbody = " +\n".join('            "%s"' % c for c in chunks)
    src = """// <auto-generated>
// Generated by tools/fonts/gen_arabic_tables.py from %s and Python unicodedata %s. Do not edit by hand.
// </auto-generated>
namespace ChibiClash
{
    static partial class RtlText
    {
        const int JoinFirst = 0x%04X, JoinLast = 0x%04X;

        /// <summary>Joining type per code point JoinFirst..JoinLast: D dual, R right, L left, C causing, T transparent, U none.</summary>
        static readonly string JoinTypes =
%s;

        /// <summary>Rows of five: base letter, isolated, final, initial, medial presentation form (0 = none).</summary>
        static readonly int[] FormTable =
        {
%s
        };
    }
}
""" % (version, unicodedata.unidata_version, FIRST, LAST, jbody, body)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    print("wrote %s (%d letters with forms)" % (OUT, len(forms)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
